    # 49.x otherwise). cypack/ormsgpack/cyclonedds-nightly are mandatory runtime
    # deps — cypack is the FIRST import in xensesdk/__init__.py and
    # ormsgpack/cyclonedds are needed by the ezros layer — so they must be
