# Installs or upgrades ONE package to >=min_version. `--upgrade-package`, not
# `--upgrade`: uv's `--upgrade` drops the prefer-installed rule for the whole
# resolution, so it also walks every dependency up to the newest release --
# which is how conda-owned packages get overwritten (check_conda_uv_consistency).
ensure_python_package_min_version() {
    local package_name=$1
    local min_version=$2

    local current_version
    current_version="$(python - "$package_name" <<'PY'
import sys
from importlib.metadata import PackageNotFoundError, version

package_name = sys.argv[1]

try:
    print(version(package_name))
except PackageNotFoundError:
    print("")
PY
)"

    if [[ -z "$current_version" ]]; then
        echo "[python] Installing missing package: $package_name>=$min_version"
        uv pip install --upgrade-package "$package_name" "$package_name>=$min_version"
        return
    fi

    local is_compatible
    is_compatible="$(python - "$current_version" "$min_version" <<'PY'
import sys

from packaging.version import Version

current_version, min_version = sys.argv[1], sys.argv[2]
print("yes" if Version(current_version) >= Version(min_version) else "no")
PY
)"

    if [[ "$is_compatible" == "yes" ]]; then
        echo "[python] Keeping $package_name==$current_version"
    else
        echo "[python] Upgrading $package_name from $current_version to >=$min_version"
        uv pip install --upgrade-package "$package_name" "$package_name>=$min_version"
    fi
}

# Report packages that conda and uv both own at different versions.
#
# conda tracks its files in conda-meta/<pkg>.json; uv/pip track theirs in
# <pkg>.dist-info/RECORD, and neither reads the other's ledger. uv CAN see
# conda's dist-info, so `uv pip install` over a conda package uninstalls it
# cleanly on the pip side -- but conda-meta still claims ownership. conda
# cannot see RECORD at all, so the next `mamba env update` relinks conda's
# copy over uv's and leaves every file uv added that conda's list omits.
# When the two versions moved a module into a package (pip's build_env.py ->
# build_env/, numpy's ctypeslib.py -> ctypeslib/) the leftover package
# shadows the module and the import dies.
#
# Only flags packages whose file sets actually overlap: conda's C++ spdlog
# (include/, lib/) and the PyPI spdlog Python binding (site-packages/) share
# a name but no files, and that is fine.
check_conda_uv_consistency() {
    python - "$CONDA_PREFIX" <<'PYEOF'
import csv, glob, json, os, re, sys

prefix = sys.argv[1]
sp = f"lib/python{sys.version_info.major}.{sys.version_info.minor}/site-packages/"

def conda_pkgs():
    for meta in glob.glob(os.path.join(prefix, "conda-meta", "*.json")):
        try:
            d = json.load(open(meta))
        except Exception:
            continue
        if d.get("name"):
            yield d["name"], d.get("version"), {
                f for f in d.get("files", []) if not f.endswith(".pyc")
            }

def dist_infos(name):
    pats = {name, name.replace("-", "_"), name.replace("_", "-")}
    seen = {}
    for pat in pats:
        for di in glob.glob(os.path.join(prefix, sp + pat + "-*.dist-info")):
            m = re.match(r".*-([^-]+)\.dist-info$", os.path.basename(di))
            rec = os.path.join(di, "RECORD")
            if not m or not os.path.exists(rec):
                continue
            files = set()
            with open(rec, newline="") as fh:
                for row in csv.reader(fh):
                    if row and row[0] and not row[0].endswith(".pyc"):
                        files.add(os.path.normpath(os.path.join(sp, row[0])))
            seen[m.group(1)] = (di, files)
    return seen

bad = []
for name, cver, cfiles in conda_pkgs():
    for uver, (di, ufiles) in dist_infos(name).items():
        if uver == cver or not (cfiles & ufiles):
            continue
        missing = sum(1 for f in cfiles if not os.path.exists(os.path.join(prefix, f)))
        di_rel = os.path.relpath(di, prefix)
        extra = sorted(f for f in ufiles - cfiles if not f.startswith(di_rel))
        bad.append((name, cver, uver, len(cfiles & ufiles), missing, len(cfiles), di, extra))

# The per-user site directory (~/.local/lib/pythonX.Y/site-packages) is not part
# of this env but conda envs inherit it, so a `pip install --user` anywhere on the
# host can shadow env packages. setup_env.sh sets PYTHONNOUSERSITE=1 to keep it off
# sys.path; this catches the case where that has been lost or overridden.
import site

shadow = []
usersite = site.getusersitepackages()
if site.ENABLE_USER_SITE and usersite in sys.path and os.path.isdir(usersite):
    def scan(d):
        found = {}
        for pat in ("*.dist-info", "*.egg-info"):
            for path in glob.glob(os.path.join(d, pat)):
                m = re.match(r"(.+)-([^-]+)\.(?:dist|egg)-info$", os.path.basename(path))
                if m:
                    found[m.group(1).lower().replace("_", "-")] = m.group(2)
        return found
    env_pkgs, user_pkgs = scan(os.path.join(prefix, sp)), scan(usersite)
    for name, uver in sorted(user_pkgs.items()):
        ever = env_pkgs.get(name)
        if ever != uver:
            shadow.append((name, ever or "-- (only in ~/.local)", uver))

if not bad and not shadow:
    print("[OK]    conda/uv package ownership is consistent.")
    print("[OK]    ~/.local site-packages is not on sys.path.")
    sys.exit(0)

if shadow:
    print("[WARN]  ~/.local/lib site-packages is on sys.path and disagrees with the env.")
    print("[WARN]  Whichever sorts first on sys.path wins, which is not something to")
    print("[WARN]  rely on. Re-run setup_env.sh, or set PYTHONNOUSERSITE=1 by hand:")
    print("[WARN]    conda env config vars set PYTHONNOUSERSITE=1 -n $CONDA_DEFAULT_ENV")
    print(f"[WARN]  {'package':22s} {'in env':22s} {'in ~/.local'}")
    for name, ever, uver in shadow:
        print(f"[WARN]  {name:22s} {ever:22s} {uver}")
    if bad:
        print("[WARN]")

if not bad:
    sys.exit(0)

print("[WARN]  These packages are owned by BOTH conda and uv at different versions.")
print("[WARN]  The next `mamba env update` will relink conda's copy over uv's and")
print("[WARN]  leave uv's extra files behind, which is how pip broke with")
print("[WARN]  \"ImportError: cannot import name 'get_runnable_pip'\".")
print(f"[WARN]  {'package':22s} {'conda-meta':12s} {'on disk':12s} {'shared':>7s} {'conda files gone':>17s}")
for name, cver, uver, shared, missing, total, _, _ in sorted(bad):
    print(f"[WARN]  {name:22s} {cver:12s} {uver:12s} {shared:7d} {f'{missing}/{total}':>17s}")
print("[WARN]  Fix by making one side own each: pin it in conda_environment.yaml to")
print("[WARN]  the version the wheel stack needs, or stop uv from upgrading it")
print("[WARN]  (`uv pip install --upgrade` upgrades every dependency in the")
print("[WARN]  resolution, not just the named package; use --upgrade-package).")
print("[WARN]  To put this env back on conda's copy right now, per package:")
for name, cver, uver, _, _, _, di, extra in sorted(bad):
    print(f"[WARN]    mamba install -p {prefix} -y --force-reinstall '{name}=={cver}'")
    print(f"[WARN]    rm -rf '{di}'")
    if extra:
        paths = " ".join(f"'{os.path.join(prefix, f)}'" for f in extra[:4])
        more = f"  # +{len(extra) - 4} more, see its RECORD" if len(extra) > 4 else ""
        print(f"[WARN]    rm -f {paths}{more}")
PYEOF
}

# ── Hardware module: ARX5 ─────────────────────────────────────────────────────

install_arx5() {
    echo ""
    echo "══════════════════════════════════════════"
    echo " ARX5 SDK  →  pyarx"
    echo "══════════════════════════════════════════"

    local SDK_DIR="$PROJECT_ROOT/third_party/ARX5_SDK"
    if [[ ! -d "$SDK_DIR" ]]; then
        echo "ERROR: $SDK_DIR not found."
        echo "  Run: git submodule update --init third_party/ARX5_SDK"
        return 1
    fi

    # The PyPI spdlog package installs conflicting C++ headers — remove it first.
    uv pip uninstall spdlog 2>/dev/null || true

    bash "$SDK_DIR/build_python.sh"

    write_sitecustomize
    echo "[arx5] Done. Verify with: python -c 'import pyarx; print(pyarx)'"
}

# ── Hardware module: Flexiv ───────────────────────────────────────────────────

install_flexiv() {
    echo ""
    echo "══════════════════════════════════════════"
    echo " libpyflexiv  →  flexiv_rt"
    echo "══════════════════════════════════════════"

    local LIB_DIR="$PROJECT_ROOT/third_party/libpyflexiv"
    local RDK_INSTALL="${RDK_INSTALL_PATH:-$HOME/rdk_install}"

    if [[ ! -d "$LIB_DIR" ]]; then
        echo "ERROR: $LIB_DIR not found."
        echo "  Run: git submodule update --init third_party/libpyflexiv"
        return 1
    fi

    # The vendored RDK deps (tinyxml2 8.0.0, foonathan_memory, Fast-CDR,
    # Fast-DDS) are pinned to ancient releases whose CMakeLists declare
    # cmake_minimum_required() < 3.5 AND explicitly cmake_policy(SET CMP0063
    # OLD). CMake 4.x (shipped in our conda env) rejects BOTH: the min version
    # (recoverable via CMAKE_POLICY_VERSION_MINIMUM=3.5) AND — fatally —
    # cmake_policy(SET CMP0063 OLD), which errors with "Policy CMP0063 may not
    # be set to OLD behavior because this version of CMake no longer supports
    # it" and has NO override. So a real CMake < 4.0 is mandatory. The deps'
    # *installed* package configs can trip cmake 4.x at find_package() time too,
    # so the binding (Stage 2) is built with the same legacy cmake.
    local LEGACY_CMAKE=""
    for _c in /usr/bin/cmake cmake3; do
        _cpath="$(command -v "$_c" 2>/dev/null)" || continue
        if "$_cpath" --version | head -1 | grep -qE 'version [123]\.'; then
            LEGACY_CMAKE="$_cpath"
            break
        fi
    done
    if [[ -z "$LEGACY_CMAKE" ]]; then
        # No system CMake < 4.0. Kitware's apt repo now ships only 4.x, so
        # `apt-get install cmake` can't help. Provision cmake<4 (3.31.x) from
        # PyPI into an isolated uv venv — a self-contained binary, no sudo, and
        # it does NOT disturb the conda env's cmake 4.x. Cached across runs.
        # NB: use the wheel's bundled data/bin/cmake directly; the venv bin/cmake
        # console-script wrapper misresolves outside an activated venv.
        local CMAKE3_VENV="${XDG_CACHE_HOME:-$HOME/.cache}/lerobot-xense/cmake3-venv"
        LEGACY_CMAKE="$(compgen -G "$CMAKE3_VENV/lib/python*/site-packages/cmake/data/bin/cmake" 2>/dev/null | head -1 || true)"
        if [[ -z "$LEGACY_CMAKE" || ! -x "$LEGACY_CMAKE" ]]; then
            echo "[flexiv] No system CMake < 4.0 found — provisioning cmake<4 from PyPI"
            echo "[flexiv]   into $CMAKE3_VENV (one-time; tinyxml2/Fast-DDS need CMP0063 OLD)"
            uv venv --python 3.12 "$CMAKE3_VENV" >/dev/null \
                && uv pip install --quiet --python "$CMAKE3_VENV/bin/python" "cmake<4"
            LEGACY_CMAKE="$(compgen -G "$CMAKE3_VENV/lib/python*/site-packages/cmake/data/bin/cmake" 2>/dev/null | head -1 || true)"
        fi
        if [[ -z "$LEGACY_CMAKE" || ! -x "$LEGACY_CMAKE" ]] \
           || ! "$LEGACY_CMAKE" --version | head -1 | grep -qE 'version 3\.'; then
            echo "[flexiv] ERROR: could not provision a CMake < 4.0 to build flexiv_rt"
            echo "[flexiv]        (tinyxml2/Fast-DDS use CMP0063 OLD, removed in CMake 4)."
            echo "[flexiv]        Install one manually, e.g.:  uv tool install 'cmake<4'"
            return 1
        fi
    fi
    # Shim it ahead of conda's cmake 4.x on PATH. Bare `cmake` calls inside the
    # submodule build scripts and the pip build backend then resolve to it.
    local CMAKE_SHIM
    CMAKE_SHIM="$(mktemp -d)"
    ln -sf "$LEGACY_CMAKE" "$CMAKE_SHIM/cmake"
    echo "[flexiv] Using $("$LEGACY_CMAKE" --version | head -1) ($LEGACY_CMAKE) for all flexiv builds"

    # Stage 1: build ~/rdk_install (RDK static lib + its C++ deps).
    # Idempotent — skip if a previous run already populated it.
    if [[ ! -f "$RDK_INSTALL/include/flexiv/rdk/robot.hpp" ]]; then
        echo "[flexiv] Building RDK + C++ dependencies into $RDK_INSTALL"
        echo "[flexiv] (one-time, ~10-30 min: eigen, spdlog, tinyxml2, foonathan_memory, Fast-CDR, Fast-DDS)"

        # flexiv_rdk is a nested submodule of libpyflexiv; ensure it is present.
        if [[ ! -f "$LIB_DIR/flexiv_rdk/thirdparty/build_and_install_dependencies.sh" ]]; then
            echo "[flexiv] Initializing flexiv_rdk submodule..."
            git -C "$LIB_DIR" submodule update --init flexiv_rdk || {
                echo "[flexiv] ERROR: failed to init flexiv_rdk submodule."
                return 1
            }
        fi

        # Subshell so the PATH/policy overrides don't leak to other installers.
        (
            set -e
            export PATH="$CMAKE_SHIM:$PATH"
            export CMAKE_POLICY_VERSION_MINIMUM=3.5  # belt-and-braces for < 3.5 mins

            # Force Fast-DDS to use its OWN vendored asio, not the system one.
            # install_Fast-DDS.sh hardcodes -DTHIRDPARTY_Asio=ON, which means
            # "use the bundle only if asio isn't found elsewhere". If the host has
            # apt `libasio-dev` (present on some 22.04 boxes, absent on the 24.04
            # box this was first tested on), CMake's find_path resolves asio to
            # /usr/include and — because that's a system prefix — emits NO -I flag.
            # The conda cross-compiler only searches its own sysroot, never the
            # host /usr/include, so the fastrtps build then dies with
            # "fatal error: asio.hpp: No such file or directory".
            # find_path searches CMAKE_PREFIX_PATH (this env var included) BEFORE
            # the system dirs, so prepending Fast-DDS's bundled asio prefix makes
            # configure resolve there — a non-system path CMake passes with -I —
            # regardless of whether libasio-dev is installed. The path need not
            # exist yet: it is created by the submodule init inside the build
            # script and only read at Fast-DDS configure time. We can't fix this
            # in install_Fast-DDS.sh itself since thirdparty/ is vendored.
            export CMAKE_PREFIX_PATH="$LIB_DIR/flexiv_rdk/thirdparty/cloned/Fast-DDS/thirdparty/asio/asio${CMAKE_PREFIX_PATH:+:$CMAKE_PREFIX_PATH}"

            cd "$LIB_DIR/flexiv_rdk/thirdparty"
            bash build_and_install_dependencies.sh "$RDK_INSTALL" "$(nproc)"

            # Install flexiv_rdk itself (headers + prebuilt static lib) into RDK_INSTALL.
            cd "$LIB_DIR/flexiv_rdk"
            rm -rf build && mkdir -p build && cd build
            cmake .. \
                -DCMAKE_INSTALL_PREFIX="$RDK_INSTALL" \
                -DCMAKE_PREFIX_PATH="$RDK_INSTALL"
            cmake --build . --target install --config Release -j"$(nproc)"
        ) || {
            echo "[flexiv] ERROR: RDK dependency build failed (see output above)."
            return 1
        }
        echo "[flexiv] RDK install complete: $RDK_INSTALL"
    else
        echo "[flexiv] Reusing existing RDK install: $RDK_INSTALL"
    fi

    # Stage 2: build Python bindings (inside conda env, with the legacy cmake)
    # IMPORTANT: only pass ~/rdk_install as CMAKE_PREFIX_PATH.
    # Do NOT include $CONDA_PREFIX — conda contains a different spdlog version
    # that will cause header conflicts (see third_party/libpyflexiv/README.md).
    local BUILD_DIR="$LIB_DIR/build"
    rm -rf "$BUILD_DIR"
    mkdir -p "$BUILD_DIR"

    # Pin tinyxml2 to the STATIC build inside ~/rdk_install. The conda env also
    # ships tinyxml2 (11.x, pulled in by urdfdom / ros-humble-tinyxml2-vendor)
    # with a tinyxml2-config.cmake exposing a SHARED target. fastrtps-config.cmake
    # does find_package(TinyXML2) — and CMake only matches that against filenames
    # `TinyXML2Config.cmake` or `tinyxml2-config.cmake`. The RDK deps install the
    # config as `tinyxml2Config.cmake` (lowercase + capital C), which does NOT
    # match, so find_package(TinyXML2) silently picks up conda's shared 11.x.
    # The binding then calls Fast-DDS (compiled against tinyxml2 8.0.0) through a
    # different-ABI tinyxml2 at runtime → segfault in
    # XMLProfileManager::loadDefaultXMLFile() the instant a Robot is created.
    #
    # Fix: drop a matching-named alias next to the static config so
    # find_package(TinyXML2) resolves to 8.0.0, and pin TinyXML2_DIR to it
    # (note the exact PascalCase — the hint var must match the find_package name).
    local TX2_CMAKE_DIR="$RDK_INSTALL/lib/cmake/tinyxml2"
    if [[ -f "$TX2_CMAKE_DIR/tinyxml2Config.cmake" ]]; then
        ln -sf tinyxml2Config.cmake "$TX2_CMAKE_DIR/tinyxml2-config.cmake"
        [[ -f "$TX2_CMAKE_DIR/tinyxml2ConfigVersion.cmake" ]] && \
            ln -sf tinyxml2ConfigVersion.cmake "$TX2_CMAKE_DIR/tinyxml2-config-version.cmake"
    fi

    "$LEGACY_CMAKE" \
        -S "$LIB_DIR" \
        -B "$BUILD_DIR" \
        -DCMAKE_BUILD_TYPE=Release \
        -DCMAKE_PREFIX_PATH="$RDK_INSTALL" \
        -DTinyXML2_DIR="$TX2_CMAKE_DIR" \
        -DPython3_EXECUTABLE="$(which python)"

    "$LEGACY_CMAKE" --build "$BUILD_DIR" -j"$(nproc)"

    # The editable install re-runs the build backend, which calls bare `cmake`;
    # the shim on PATH keeps it on the legacy cmake too.
    PATH="$CMAKE_SHIM:$PATH" uv pip install -e "$LIB_DIR" --no-build-isolation

    write_sitecustomize
    grant_rt_scheduling
    echo "[flexiv] RT SDK done. Verify with: python -c 'import flexiv_rt; print(flexiv_rt)'"

    # Install Flexiv NRT Python SDK from PyPI
    echo ""
    echo "[flexiv] Installing NRT SDK (flexivrdk)..."
    uv pip install "flexivrdk==1.8.0"
    echo "[flexiv] NRT SDK done. Verify with: python -c 'import flexivrdk; print(flexivrdk)'"
}

# ── Hardware module: Pico4 ────────────────────────────────────────────────────

# Install the XenseVR PC Service daemon from its .deb. The package (~116 MB) is
# the binary service the Pico4 teleop/tracker talks to (installs to
# /opt/apps/roboticsservice); it is NOT vendored in-repo. By default,
# setup_env.sh downloads the matching-arch asset directly from the GitHub release
# ($XENSEVR_DEB_URL overrides the default release URL).
# $XENSEVR_DEB remains an explicit path override for offline/patched builds; no
# implicit dist/ or ~/Downloads cache lookup is done.
# Non-fatal on download failure: install_pico4() checks for the SDK afterwards
# and reports the real problem there. Idempotent: same installed version is skipped.
install_xensevr_service() {
    echo ""
    echo "── XenseVR PC Service (.deb daemon) ──"

    local ARCH DEB_VER DEB_URL DEB
    ARCH="$(dpkg --print-architecture 2>/dev/null || echo amd64)"   # amd64 | arm64
    DEB_VER="0.2.1"

    # 0.2.x ships amd64 only. Without this, an arm64 host would build a URL
    # for an asset that does not exist and fail with a bare 404 — pinning it
    # to the last release that has an arm64 build is both truthful and
    # working, at the cost of no Pico camera support there.
    if [[ "$ARCH" == "arm64" && -z "${XENSEVR_DEB_URL:-}${XENSEVR_DEB:-}" ]]; then
        DEB_VER="0.1.0"
        echo "  NOTE: arm64 detected — pinning to v${DEB_VER}, the newest release with"
        echo "        an arm64 asset. 0.2.x (Pico camera support) is amd64-only, and"
        echo "        XenseVR-PC-Service dropped its aarch64 tree, so building one is"
        echo "        no longer a matter of running a script in that repository."
    fi

    DEB_URL="${XENSEVR_DEB_URL:-https://github.com/XenseRobotics-AI/XenseVR-PC-Service/releases/download/v${DEB_VER}/XenseVR-PC-Service_${DEB_VER}_${ARCH}.deb}"

    local WANT INSTALLED STATUS
    # Check the status, not just the version. `dpkg -r` leaves the package in
    # `deinstall ok config-files`, and dpkg-query still reports its version
    # there — so matching on the version alone declares a daemon installed
    # when /opt/apps/roboticsservice is gone, skips the install, and fails
    # later somewhere far less obvious.
    STATUS="$(dpkg-query -W -f='${Status}' xensevr-pc-service 2>/dev/null || true)"
    INSTALLED="$(dpkg-query -W -f='${Version}' xensevr-pc-service 2>/dev/null || true)"

    # Decide before downloading. DEB_VER already names the version this script
    # would install, so fetching 116 MB only to read the same number back out of
    # the package is waste on every re-run of --install. An explicit override is
    # exempt: it can be a different build carrying the same version, and only
    # the file itself can say.
    if [[ -z "${XENSEVR_DEB:-}${XENSEVR_DEB_URL:-}" && "$STATUS" == "install ok installed" && "$INSTALLED" == "$DEB_VER" ]]; then
        echo "  xensevr-pc-service $INSTALLED already installed — skipping."
        return 0
    fi

    DEB="${XENSEVR_DEB:-}"
    if [[ -n "$DEB" ]]; then
        if [[ ! -f "$DEB" ]]; then
            echo "  WARN: XENSEVR_DEB points to a missing file: $DEB"
            echo "  WARN: skipping service install."
            return 0
        fi
        echo "  Using explicit .deb override: $DEB"
    else
        DEB="${TMPDIR:-/tmp}/XenseVR-PC-Service_${DEB_VER}_${ARCH}.deb"
        if [[ -f "$DEB" ]] && dpkg-deb -f "$DEB" Version >/dev/null 2>&1; then
            echo "  Reusing previously downloaded $DEB"
        else
            # An unreadable leftover is worth less than the bandwidth to replace it.
            rm -f "$DEB"
            echo "  Downloading ${ARCH} asset from:"
            echo "    $DEB_URL"
            # ~116 MB. Retry and resume rather than losing the whole transfer to
            # one dropped connection — this package is now the only source of the
            # client SDK the Python bindings link against, so a failure here is
            # not something a local build can paper over.
            #
            # Staged through .part deliberately: handing a *complete* file to
            # `curl -C -` asks for a range that starts at EOF, the server answers
            # 416, and --retry-all-errors then retries that five times before
            # giving up. Only a partial transfer is ever resumed.
            local RETRY=(--retry 5 --retry-delay 2)
            if curl --help all 2>/dev/null | grep -q -- '--retry-all-errors'; then
                RETRY+=(--retry-all-errors)   # curl >= 7.71; covers a mid-transfer drop
            fi
            if ! curl -fL "${RETRY[@]}" -C - "$DEB_URL" -o "$DEB.part"; then
                echo "  WARN: download failed — skipping service install."
                echo "  The partial file is kept at $DEB.part — re-run to resume it."
                echo "  Or get it from https://github.com/XenseRobotics-AI/XenseVR-PC-Service/releases"
                echo "  then: sudo dpkg -i XenseVR-PC-Service_*_${ARCH}.deb"
                return 0
            fi
            mv "$DEB.part" "$DEB"
        fi
    fi

    WANT="$(dpkg-deb -f "$DEB" Version 2>/dev/null)"
    if [[ "$STATUS" == "install ok installed" && "$INSTALLED" == "$WANT" ]]; then
        echo "  xensevr-pc-service $INSTALLED already installed — skipping."
        return 0
    fi

    echo "  Installing xensevr-pc-service ${WANT:-?} from: $DEB"
    sudo dpkg -i "$DEB" || sudo apt-get install -f -y
    echo "  Installed to /opt/apps/roboticsservice. Start the service with:"
    echo "    /opt/apps/roboticsservice/runService.sh"
}

install_pico4() {
    echo ""
    echo "══════════════════════════════════════════"
    echo " XenseVR-PC-Service  →  xensevr_pc_service_sdk"
    echo "══════════════════════════════════════════"

    local PYBIND_DIR="$PROJECT_ROOT/src/lerobot/teleoperators/pico4/xensevr-pc-service-pybind"

    # Install the PC Service daemon (.deb) the Python SDK will talk to. It also
    # ships the client SDK the bindings link against, which is why there is no
    # longer a XenseVR-PC-Service submodule to compile: the .deb's
    # libPXREARobotSDK.so is the same artifact that build used to produce, and
    # keeping a 33 MiB shallow checkout of prebuilt gRPC archives around to
    # rebuild it cost more than it was worth. The trade is that an SDK source
    # fix now has to travel through a .deb release rather than through
    # `--install`.
    install_xensevr_service

    # Take the header and .so straight out of the installed package. SDK/x64 on
    # amd64, SDK/arm64 on arm64 — the names come from the service's own install
    # step, not from dpkg's architecture strings.
    local SDK_ROOT="/opt/apps/roboticsservice/SDK"
    local SDK_LIBDIR
    case "$(dpkg --print-architecture 2>/dev/null || echo amd64)" in
        arm64) SDK_LIBDIR="$SDK_ROOT/arm64" ;;
        *)     SDK_LIBDIR="$SDK_ROOT/x64" ;;
    esac

    if [[ ! -f "$SDK_ROOT/include/PXREARobotSDK.h" || ! -f "$SDK_LIBDIR/libPXREARobotSDK.so" ]]; then
        echo "ERROR: the XenseVR PC Service SDK is not on this host."
        echo "  Expected:"
        echo "    $SDK_ROOT/include/PXREARobotSDK.h"
        echo "    $SDK_LIBDIR/libPXREARobotSDK.so"
        echo "  Both come from the xensevr-pc-service .deb, which the step above"
        echo "  installs. If that step warned about a failed download, fix that"
        echo "  first — the bindings cannot be built without it."
        return 1
    fi

    # Both architectures stage flat into include/ and lib/; the pybind
    # CMakeLists looks there on every UNIX host. nlohmann is not in the .deb —
    # it comes from conda (nlohmann_json in conda_environment.yaml) and the
    # CMakeLists find_package()s it.
    mkdir -p "$PYBIND_DIR/include" "$PYBIND_DIR/lib"
    cp "$SDK_ROOT/include/PXREARobotSDK.h" "$PYBIND_DIR/include/"
    cp "$SDK_LIBDIR/libPXREARobotSDK.so" "$PYBIND_DIR/lib/"

    # Build and install the Python bindings
    pushd "$PYBIND_DIR" > /dev/null
    rm -rf build *.egg-info
    uv pip uninstall xensevr_pc_service_sdk 2>/dev/null || true
    uv pip install . --no-build-isolation
    popd > /dev/null

    echo "[pico4] Done. Verify with: python -c 'import xensevr_pc_service_sdk; print(xensevr_pc_service_sdk)'"
}

