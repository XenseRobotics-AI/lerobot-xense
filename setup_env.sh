#!/bin/bash

# Check the operating system
OS_NAME=$(uname -s)
OS_VERSION=""

if [[ "$OS_NAME" == "Linux" ]]; then
    if command -v lsb_release &>/dev/null; then
        OS_VERSION=$(lsb_release -rs)
    elif [[ -f /etc/os-release ]]; then
        . /etc/os-release
        OS_VERSION=$VERSION_ID
    fi
    # Tested on Ubuntu 22.04 (jammy) and 24.04 (noble). The host was upgraded
    # 22.04 → 24.04, which bumps the system toolchain to GCC 13 — fine because
    # the hardware SDKs build against the conda cross-compiler, not system GCC.
    if [[ "$OS_VERSION" != "22.04" && "$OS_VERSION" != "24.04" ]]; then
        echo "Warning: This script has only been tested on Ubuntu 22.04 and 24.04"
        echo "Your system is running Ubuntu $OS_VERSION."
        read -p "Do you want to continue anyway? (y/N): " -n 1 -r
        echo
        if [[ ! $REPLY =~ ^[Yy]$ ]]; then
            echo "Installation cancelled."
            exit 1
        fi
    fi
else
    echo "Unsupported operating system: $OS_NAME"
    exit 1
fi

echo "Operating system check passed: $OS_NAME $OS_VERSION"

# Large PyPI wheels such as torch can exceed uv's default 30s timeout on
# slower links. Allow callers to override, but use a safer default for setup.
export UV_HTTP_TIMEOUT="${UV_HTTP_TIMEOUT:-300}"

# Resolve script directory so files can be referenced reliably
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SCRIPT_NAME="$(basename "${BASH_SOURCE[0]}")"
PROJECT_ROOT="$SCRIPT_DIR"

# Conda environment yaml file (canonical name)
CONDA_ENV_FILE="$SCRIPT_DIR/conda_environment.yaml"
if [[ ! -f "$CONDA_ENV_FILE" ]]; then
    echo "Error: conda environment yaml not found: $CONDA_ENV_FILE"
    exit 1
fi

# ── Conda environment creation ────────────────────────────────────────────────

create_environment() {
    local CONDA_CMD=$1
    local ENV_NAME=$2

    # Deactivate current environment if any (use conda deactivate for both conda and mamba)
    conda deactivate 2>/dev/null || true

    # Remove existing environment if it exists
    if $CONDA_CMD env list | grep -q "^$ENV_NAME "; then
        echo "Removing existing environment '$ENV_NAME'..."
        if ! $CONDA_CMD env remove -n "$ENV_NAME" -y; then
            echo "Error: Failed to remove existing environment '$ENV_NAME'."
            return 1
        fi
    fi

    # Create new environment from conda_environment.yaml
    if ! $CONDA_CMD env create -f "$CONDA_ENV_FILE" -n "$ENV_NAME"; then
        echo "Error: Failed to create $CONDA_CMD environment '$ENV_NAME' from: $CONDA_ENV_FILE"
        return 1
    fi

    echo "$CONDA_CMD environment '$ENV_NAME' created from: $CONDA_ENV_FILE"

    echo -e "[INFO] Created $CONDA_CMD environment named '$ENV_NAME'.\n"
    echo -e "\t\t1. To activate the environment, run:                $CONDA_CMD activate $ENV_NAME"
    echo -e "\t\t2. To install all dependencies, run:                bash $SCRIPT_NAME --install"
    echo -e "\t\t3. To deactivate the environment, run:              conda deactivate"
    echo -e "\n"
}

# ── Shared helpers for hardware installation ──────────────────────────────────

# Write sitecustomize.py that preloads conda's own copies of libraries the system
# also ships, at Python startup: libstdc++ (CXXABI_1.3.15 for GCC 14+ extensions
# like ARX5 / flexiv_rt) and FFmpeg 8 (so torchcodec uses conda's FFmpeg instead of
# silently falling back to the system's). The generated file explains both.
#
# Preloading rather than LD_LIBRARY_PATH is forced: grant_rt_scheduling below gives
# the interpreter cap_sys_nice, which puts it in secure-execution mode (AT_SECURE=1)
# where the kernel strips LD_LIBRARY_PATH from the environment outright. Verified on
# this host: getcap reports cap_sys_nice=ep and LD_LIBRARY_PATH reads as unset inside
# the process even when exported.
write_sitecustomize() {
    local PY_VER
    PY_VER="$(python -c 'import sys; print(f"python{sys.version_info.major}.{sys.version_info.minor}")')"
    local SITE_DIR="${CONDA_PREFIX}/lib/${PY_VER}/site-packages"
    local TARGET="${SITE_DIR}/sitecustomize.py"

    # Version the file so adding a preloader actually reaches environments that
    # already have an older sitecustomize. (The previous guard matched on
    # "RTLD_GLOBAL", which every version contains, so it could never update one.)
    local SITECUSTOMIZE_VERSION="v4-ffmpeg-local"

    if [[ -f "$TARGET" ]] && grep -q "sitecustomize $SITECUSTOMIZE_VERSION" "$TARGET" 2>/dev/null; then
        echo "[sitecustomize] Already configured ($SITECUSTOMIZE_VERSION)."
        return
    fi
    echo "[sitecustomize] Writing conda library preloader ($SITECUSTOMIZE_VERSION) → $TARGET"
    cat > "$TARGET" << 'PYEOF'
"""Preload conda's own copies of libraries that clash with the system's.

Auto-generated by setup_env.sh — sitecustomize v4-ffmpeg-local. Do not edit by hand;
change write_sitecustomize() in setup_env.sh and re-run the installer.

Both entries below fix the same shape of bug: a C extension resolves a SONAME to
the system's copy of a library while the rest of the process is using conda's,
and the two disagree. Loading conda's first, RTLD_GLOBAL, makes the conda copy
win for everything that comes later.

1. libstdc++ — extensions compiled with GCC 14+ need CXXABI_1.3.15, which the
   system libstdc++ may be too old to provide.

2. FFmpeg 8 — torchcodec tries FFmpeg 8, 7, 6, 5, 4 in turn and keeps the first
   that fully loads. Without this preload it silently lands on the SYSTEM FFmpeg
   6, even though conda ships a complete FFmpeg 8 (libavutil 60 + libav{codec,
   format,device} 62): torchcodec's own FFmpeg-8 binaries cannot resolve conda's
   SONAMEs at dlopen time, and pyav's bundled FFmpeg 7 is auditwheel-renamed
   (libavutil-<hash>.so.59) so it never matches either.

   Falling back to the system FFmpeg 6 is fragile as well as unintended: that
   chain pulls in the system libncursesw, which — once anything has loaded
   conda's libtinfo — fails with "undefined symbol: _nc_safe_fopen". `import
   readline` is enough to trigger it, which is why the whole video test suite
   fails under pytest but passes in a plain interpreter. The error surfaces as
   "Could not load libtorchcodec ... FFmpeg is not properly installed", pointing
   nowhere near the actual cause.

   Preloading conda's set makes torchcodec select FFmpeg 8 and stay there.

   The FFmpeg entries MUST be RTLD_LOCAL. Loading them RTLD_GLOBAL fixes
   torchcodec but segfaults pyav: pyav carries its own auditwheel-renamed
   FFmpeg 7, and with FFmpeg 8's av_* symbols in the global scope pyav's calls
   bind across ABI versions. Encoding then crashes (test_streaming_video_encoder,
   test_datasets, test_aggregate, test_dataset_tools all core-dumped) — a strictly
   worse trade, since encoding is what recording depends on. RTLD_LOCAL still
   satisfies torchcodec's dlopen, because the loader resolves a dependency
   against any already-loaded object with a matching SONAME regardless of mode;
   it just keeps conda's symbols out of the global namespace. Verified: with
   RTLD_LOCAL, torchcodec reports FFmpeg 8 while pyav still reports libavutil 59.

Why not LD_LIBRARY_PATH instead of preloading at all: setup_env.sh grants the
interpreter cap_sys_nice (see grant_rt_scheduling, needed for the RT control
threads). A binary with file capabilities runs in secure-execution mode, where
the dynamic linker ignores LD_LIBRARY_PATH entirely. Preloading is what is left.
"""
import ctypes
import os
import sys

# (filename, dlopen mode) — see the module docstring for why the modes differ.
_PRELOAD = (
    ("libstdc++.so.6", ctypes.RTLD_GLOBAL),
    # FFmpeg 8, in dependency order. LOCAL on purpose — GLOBAL breaks pyav.
    ("libavutil.so.60", ctypes.RTLD_LOCAL),
    ("libavcodec.so.62", ctypes.RTLD_LOCAL),
    ("libavformat.so.62", ctypes.RTLD_LOCAL),
    ("libavdevice.so.62", ctypes.RTLD_LOCAL),
)

# sys.prefix, not $CONDA_PREFIX: this file lives in the environment it describes,
# and sys.prefix is right whether or not the environment was activated. Keying off
# the environment variable meant every un-activated invocation — an absolute path
# to bin/python, a systemd unit, cron — silently skipped the preloads and got the
# system libraries instead.
for _name, _mode in _PRELOAD:
    _path = os.path.join(sys.prefix, "lib", _name)
    if os.path.exists(_path):
        try:
            ctypes.CDLL(_path, mode=_mode)
        except Exception:
            # Best effort: a missing or unloadable library just means the previous
            # behaviour, never a hard failure at interpreter start.
            pass
PYEOF
}

# Flexiv RDK (and the ARX5 SDK) spawn SCHED_FIFO real-time control threads. Raising
# a thread to real-time priority requires CAP_SYS_NICE; a normal user lacks it, so
# the RDK Scheduler logs "Failed to set thread priority: root privilege is required"
# and silently downgrades the 1 kHz control loop to normal scheduling (jittery, unsafe
# on real hardware). Grant the capability to the *resolved* interpreter binary (setcap
# follows the conda bin/python symlink and writes the real file). Idempotent; harmless
# for non-robot scripts since cap_sys_nice only permits raising scheduling priority.
grant_rt_scheduling() {
    local PY_REAL
    PY_REAL="$(readlink -f "${CONDA_PREFIX}/bin/python")"
    if ! command -v setcap >/dev/null 2>&1; then
        echo "[rt-sched] WARN: 'setcap' not found — install it with 'sudo apt install libcap2-bin'."
        echo "[rt-sched]       Real-time thread priority will be unavailable until then."
        return 0
    fi
    echo "[rt-sched] Granting cap_sys_nice to $PY_REAL (needs sudo)..."
    if sudo setcap cap_sys_nice=ep "$PY_REAL"; then
        echo "[rt-sched] Done. Verify with: getcap $PY_REAL"
    else
        echo "[rt-sched] WARN: setcap failed — RT control threads will run at normal priority."
    fi
}

# conda installs a udev/ directory that confuses ctypes.util.find_library("udev"),
# causing pyudev/xensesdk to crash with "OSError: .../lib/udev: Is a directory".
fix_udev_discovery() {
    if [[ -d "${CONDA_PREFIX}/lib/udev" ]]; then
        echo "[udev] Renaming ${CONDA_PREFIX}/lib/udev to avoid pyudev clash..."
        local target="${CONDA_PREFIX}/lib/udev.rules.d"
        [[ -e "$target" ]] && target="${target}.bak.$(date +%s)"
        mv "${CONDA_PREFIX}/lib/udev" "$target" || true
    fi
    if [[ -e "${CONDA_PREFIX}/lib/libudev.so.1" && ! -e "${CONDA_PREFIX}/lib/libudev.so" ]]; then
        ln -s libudev.so.1 "${CONDA_PREFIX}/lib/libudev.so" || true
    fi
}

