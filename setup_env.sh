# Top-level usage. Hardware selectors are documented by `--install --help`.
print_general_usage() {
    cat <<'USAGE'
Usage: ./setup_env.sh <command> [options]
  --conda [env_name]     Create a conda environment (requires Miniconda/Anaconda)
  --mamba [env_name]     Create a mamba environment (requires Miniforge)
  --install [hardware]   Install base package + hardware SDK bindings.
                         No hardware selector => install ALL (backward compatible).
                         Run `./setup_env.sh --install --help` for the selector list.
  --help, -h             Show this message
USAGE
}

# ── Argument parsing ──────────────────────────────────────────────────────────

# Check if an environment name is provided
if [[ -n "$2" ]]; then
    ENV_NAME="$2"
else
    ENV_NAME="lerobot-xense"
fi

# Check if the --conda parameter is passed
if [[ "$1" == "--conda" ]]; then
    # Initialize conda
    if [ -f "$HOME/miniconda3/etc/profile.d/conda.sh" ]; then
        . "$HOME/miniconda3/etc/profile.d/conda.sh"
    elif [ -f "$HOME/anaconda3/etc/profile.d/conda.sh" ]; then
        . "$HOME/anaconda3/etc/profile.d/conda.sh"
    else
        echo "Conda initialization script not found. Please install Miniconda3 or Anaconda3 or Miniforge3."
        exit 1
    fi
    create_environment "conda" "$ENV_NAME" || exit 1

# Check if the --mamba parameter is passed
elif [[ "$1" == "--mamba" ]]; then
    # Initialize mamba (miniforge)
    if [ -f "$HOME/miniforge3/etc/profile.d/conda.sh" ]; then
        . "$HOME/miniforge3/etc/profile.d/conda.sh"
    elif [ -f "$HOME/mambaforge/etc/profile.d/conda.sh" ]; then
        . "$HOME/mambaforge/etc/profile.d/conda.sh"
    else
        echo "Mamba initialization script not found. Please install Miniforge3 or Mambaforge."
        exit 1
    fi
    # Also source mamba.sh if available for full mamba support
    if [ -f "$HOME/miniforge3/etc/profile.d/mamba.sh" ]; then
        . "$HOME/miniforge3/etc/profile.d/mamba.sh"
    elif [ -f "$HOME/mambaforge/etc/profile.d/mamba.sh" ]; then
        . "$HOME/mambaforge/etc/profile.d/mamba.sh"
    fi
    create_environment "mamba" "$ENV_NAME" || exit 1

# Check if the --install parameter is passed
elif [[ "$1" == "--install" ]]; then
    # ── Hardware selector parsing ─────────────────────────────────────────────
    # Per-hardware-family flags after --install restrict which SDK bindings get
    # built. No flags => install everything (backward compatible). Arm selectors
    # auto-include the xense gripper stack (the arms drive xense grippers).
    #   ./setup_env.sh --install                     # core + ALL hardware SDKs
    #   ./setup_env.sh --install --flexiv --taccap   # core + those (+ auto xense)
    #   ./setup_env.sh --install --core              # core only, no hardware SDK
    SELECTED=""
    add_key() { case " $SELECTED " in *" $1 "*) ;; *) SELECTED="$SELECTED $1" ;; esac; }
    is_sel()  { case " $SELECTED " in *" $1 "*) return 0 ;; *) return 1 ;; esac; }
    select_all_hw() { local k; for k in arx5 flexiv pico4 xense taccap elite spacemouse dynamixel; do add_key "$k"; done; }
    print_install_usage() {
        cat <<'USAGE'
Usage: ./setup_env.sh --install [hardware selectors]
  (no selector)         core + ALL hardware SDKs (default, backward compatible)
  --all                 core + ALL hardware SDKs (explicit)
  --core, --none        core only (no hardware SDK bindings)
Per-hardware-family selectors (arms auto-include the xense gripper stack):
  --flexiv,  --bi_flexiv     Flexiv Rizon4 RT    (+ xense)
  --elite,   --bi_elite      Elite CS66 RT       (+ xense)
  --taccap,  --bi_taccap     TacCap gripper      (+ xense)
  --xense                    Xense tactile sensors + XGripper serial gripper
  --arx5,    --bi_arx5       ARX5 arm
  --pico4,   --bi_pico4      Pico4 VR teleop
  --spacemouse               3D SpaceMouse teleop
  --dynamixel, --trlc        Dynamixel / TRLC leader teleop
Examples:
  ./setup_env.sh --install --flexiv --taccap
  ./setup_env.sh --install --core
USAGE
    }
    _hw_args=("${@:2}")
    if [[ ${#_hw_args[@]} -eq 0 ]]; then
        select_all_hw
    else
        for _a in "${_hw_args[@]}"; do
            case "$_a" in
                --all)                    select_all_hw ;;
                --core|--none)            : ;;  # no-op: core is always installed
                --flexiv|--bi_flexiv)     add_key flexiv; add_key xense ;;
                --elite|--bi_elite)       add_key elite;  add_key xense ;;
                --taccap|--bi_taccap)     add_key taccap; add_key xense ;;
                --xense)                  add_key xense ;;
                --arx5|--bi_arx5)         add_key arx5 ;;
                --pico4|--bi_pico4)       add_key pico4 ;;
                --spacemouse)             add_key spacemouse ;;
                --dynamixel|--trlc)       add_key dynamixel ;;
                --help|-h)                print_install_usage; exit 0 ;;
                *) echo "[ERROR] Unknown --install selector: $_a"; echo; print_install_usage; exit 1 ;;
            esac
        done
    fi
    SELECTED="$(echo "$SELECTED" | tr -s ' ' | sed 's/^ //; s/ $//')"
    if [[ -n "$SELECTED" ]]; then
        echo "[INFO] Selected hardware SDKs: $SELECTED"
    else
        echo "[INFO] Selected hardware SDKs: (core only — no hardware bindings)"
    fi

    # Get the currently activated conda environment name
    if [[ -z "${CONDA_DEFAULT_ENV}" ]]; then
        echo "Error: No conda/mamba environment is currently activated."
        echo "Please activate an environment first with: conda/mamba activate <env_name>"
        exit 1
    fi
    ENV_NAME=${CONDA_DEFAULT_ENV}

    # Detect conda/mamba command
    if [ -f "$HOME/miniforge3/etc/profile.d/conda.sh" ]; then
        CONDA_CMD="mamba"
    else
        CONDA_CMD="conda"
    fi

    echo "[INFO] Updating conda environment '$ENV_NAME' from: $CONDA_ENV_FILE"
    if ! $CONDA_CMD env update -f "$CONDA_ENV_FILE" -n "$ENV_NAME"; then
        echo "[ERROR] Failed to update conda environment '$ENV_NAME' from: $CONDA_ENV_FILE"
        exit 1
    fi

    echo -e "\n[INFO] Conda dependencies installed/updated for '$ENV_NAME'.\n"

    # Keep ~/.local/lib/pythonX.Y/site-packages off this env's sys.path.
    #
    # conda envs inherit the per-user site directory, and this host has one:
    # a `pip install --user pillow-heif` on 2026-07-25 left 12 packages there,
    # six of which also exist in the env at different versions (pillow 12.3.0
    # vs 12.2.0, tqdm 4.68.4 vs 4.68.3, fsspec, huggingface-hub, filelock).
    # The env's site-packages currently sorts first so the env copy wins, but
    # that ordering is not something to rely on, and pillow-heif exists ONLY in
    # ~/.local -- so it is importable here despite not being a dependency of
    # this project. Deleting ~/.local is not an option: the system python3.12
    # shares it, and it belongs to the user, not to this repo.
    #
    # Exported as well as recorded, so the rest of THIS run also ignores it --
    # otherwise uv can see a ~/.local copy, consider the requirement satisfied,
    # and skip installing the package into the env.
    $CONDA_CMD env config vars set PYTHONNOUSERSITE=1 -n "$ENV_NAME" >/dev/null
    export PYTHONNOUSERSITE=1
    echo "[INFO] PYTHONNOUSERSITE=1 set for '$ENV_NAME' (ignores ~/.local site-packages)."
    # NOTE: do NOT upgrade pip here. `pip` is a conda dependency
    # (conda_environment.yaml), so conda owns those files. `uv pip install
    # --upgrade pip` writes a newer pip over them without conda knowing; the
    # next `conda env update` then relinks conda's older pip on top, leaving the
    # newer version's extra files behind (e.g. pip 26.2.1's `_internal/build_env/`
    # package shadowing 26.1.2's `_internal/build_env.py`). The result is a pip
    # that cannot import itself:
    #   ImportError: cannot import name 'get_runnable_pip' from 'pip._internal.utils.misc'
    # Nothing in this script calls `python -m pip` — every install below goes
    # through `uv pip` — so conda's pip is only there for the yaml `pip:` section.
    # If pip really must be upgraded, do it with conda/mamba, not uv.

    # Ensure editable installs (PEP 660) work without downgrading newer compatible packages.
    ensure_python_package_min_version setuptools 71.0.0
    ensure_python_package_min_version wheel 0.40.0

    # Workaround for Python ctypes.util.find_library("udev") on conda envs:
    # Hacking the udev library discovery to avoid issues with pyudev/xensesdk.
    # If $CONDA_PREFIX/lib/udev exists as a directory, Python may return that directory as the "udev" library,
    # causing pyudev/xensesdk to crash with: "OSError: .../lib/udev: Is a directory".
    fix_udev_discovery

    # evdev (pulled in by pynput) generates ecodes.c from /usr/include/linux/ at
    # build time, then compiles it with the conda cross-compiler which uses its
    # own sysroot. Ubuntu's linux-libc-dev now ships KEY_LINK_PHONE (added in
    # Linux 6.14), so evdev references it in ecodes.c, but the conda sysroot's
    # older kernel headers lack it.  Patch the sysroot header in place so the
    # conda compiler can find the constant without mixing incompatible glibc headers.
    _SYSROOT_CODES="${CONDA_PREFIX}/x86_64-conda-linux-gnu/sysroot/usr/include/linux/input-event-codes.h"
    if [[ -f "$_SYSROOT_CODES" ]] && ! grep -q "KEY_LINK_PHONE" "$_SYSROOT_CODES"; then
        echo "[INFO] Patching conda sysroot: adding KEY_LINK_PHONE to input-event-codes.h"
        printf '\n#ifndef KEY_LINK_PHONE\n#define KEY_LINK_PHONE 0x1bf  /* AL Phone Syncing, Linux 6.14 */\n#endif\n' >> "$_SYSROOT_CODES"
    fi

    echo "[INFO] Installing Lerobot from pyproject.toml"
    if uv pip install -e .; then
        echo "[INFO] Lerobot installed successfully!"
    else
        echo "[ERROR] Lerobot installation failed. See the error output above."
        exit 1
    fi

    # Verify critical package versions
    echo "[INFO] Verifying package versions..."
    TORCHCODEC_VER=$(python -c "import torchcodec; print(torchcodec.__version__)" 2>/dev/null || echo "NOT INSTALLED")
    AV_VER=$(python -c "import av; print(av.__version__)" 2>/dev/null || echo "NOT INSTALLED")
    TORCH_VER=$(python -c "import torch; print(torch.__version__)" 2>/dev/null || echo "NOT INSTALLED")
    TORCH_MAJOR_MINOR=$(get_torch_major_minor)
    EXPECTED_TORCHCODEC_VER=$(expected_torchcodec_version "$TORCH_MAJOR_MINOR")
    echo "  - torch: $TORCH_VER"
    if [[ -n "$EXPECTED_TORCHCODEC_VER" ]]; then
        echo "  - torchcodec: $TORCHCODEC_VER (should be $EXPECTED_TORCHCODEC_VER for torch $TORCH_MAJOR_MINOR)"
    else
        echo "  - torchcodec: $TORCHCODEC_VER (no compatibility override defined for torch $TORCH_VER)"
    fi
    echo "  - av (pyav): $AV_VER (should be 15.1.0)"

    if [[ -n "$EXPECTED_TORCHCODEC_VER" ]]; then
        if [[ "$(version_matches_expected_release "$TORCHCODEC_VER" "$EXPECTED_TORCHCODEC_VER")" != "yes" ]]; then
            echo "[WARN] torchcodec version mismatch! Expected $EXPECTED_TORCHCODEC_VER for torch $TORCH_MAJOR_MINOR, got $TORCHCODEC_VER"
            uv pip install "torchcodec==$EXPECTED_TORCHCODEC_VER" --force-reinstall
        fi
    else
        echo "[WARN] Skipping torchcodec pin verification for unsupported torch version: $TORCH_VER"
    fi

    if [[ "$AV_VER" != "15.1.0" ]]; then
        echo "[WARN] av (pyav) version mismatch! Expected 15.1.0, got $AV_VER"
        uv pip install av==15.1.0 --force-reinstall
    fi

    echo ""
    echo "[INFO] Installing hardware SDK bindings..."
    echo ""

    if is_sel arx5;       then install_arx5      || echo "[WARN] arx5 installation skipped or failed (see above)"; fi
    if is_sel flexiv;     then install_flexiv    || echo "[WARN] flexiv installation skipped or failed (see above)"; fi
    if is_sel pico4;      then ( install_pico4 ) || echo "[WARN] pico4 installation skipped or failed (see above)"; fi
    if is_sel xense;      then install_xense     || echo "[WARN] xense installation skipped or failed (see above)"; fi
    if is_sel taccap;     then install_taccap    || echo "[WARN] taccap installation skipped or failed (see above)"; fi
    if is_sel elite;      then install_elite     || echo "[WARN] elite installation skipped or failed (see above)"; fi
    if is_sel spacemouse; then install_spacemouse || echo "[WARN] spacemouse installation skipped or failed (see above)"; fi
    if is_sel dynamixel;  then install_dynamixel  || echo "[WARN] dynamixel-sdk installation skipped or failed (see above)"; fi


    # ── Post-install verification ────────────────────────────────────────────
    echo ""
    echo "══════════════════════════════════════════"
    echo " Post-install verification"
    echo "══════════════════════════════════════════"
    # Verify only the SDKs that were selected for install (lerobot core always).
    # spacemouse has no verify probe today — kept that way.
    _VERIFY_LINES='lerobot|import importlib.metadata as M, lerobot; print("v"+M.version("lerobot"), "->", lerobot.__file__)'
    if is_sel arx5;      then _VERIFY_LINES+=$'\n''pyarx|import importlib.metadata as M, pyarx; print("v"+M.version("pyarx"), "->", pyarx.__file__)'; fi
    if is_sel flexiv;    then _VERIFY_LINES+=$'\n''flexiv_rt|import importlib.metadata as M, flexiv_rt; print("v"+M.version("flexiv_rt"), "->", flexiv_rt.__file__)'; fi
    if is_sel pico4;     then _VERIFY_LINES+=$'\n''xensevr_pc_service_sdk|import importlib.metadata as M, xensevr_pc_service_sdk; print("v"+M.version("xensevr_pc_service_sdk"), "->", xensevr_pc_service_sdk.__file__)'; fi
    if is_sel xense;     then _VERIFY_LINES+=$'\n''xensesdk|import importlib.metadata as M, xensesdk; print("v"+M.version("xensesdk"), "->", xensesdk.__file__)'; fi
    if is_sel xense;     then _VERIFY_LINES+=$'\n''xgripper|import importlib.metadata as M, xgripper; print("v"+M.version("xgripper"), "->", xgripper.__file__)'; fi
    if is_sel xense;     then _VERIFY_LINES+=$'\n''xensesdk flash|from xensesdk.flash.linux_backend import LinuxFlashBackend; print("available" if LinuxFlashBackend().available else "NOT available")'; fi
    if is_sel taccap;    then _VERIFY_LINES+=$'\n''taccap-gripper|import importlib.metadata as M, xense.taccap; print("v"+M.version("taccap-gripper"), "->", xense.taccap.__file__)'; fi
    if is_sel elite;     then _VERIFY_LINES+=$'\n''elite_cs_sdk|import importlib.metadata as M, elite_cs_sdk; print("v"+M.version("elite_cs_sdk"), "->", elite_cs_sdk.__file__)'; fi
    if is_sel dynamixel; then _VERIFY_LINES+=$'\n''dynamixel_sdk|import importlib.metadata as M, dynamixel_sdk; print("v"+M.version("dynamixel_sdk"), "->", dynamixel_sdk.__file__)'; fi

    _VERIFY_FAIL=0
    while IFS='|' read -r _pkg _import; do
        [[ -z "$_pkg" ]] && continue
        _out="$(python -c "$_import" 2>&1)" && \
            echo "[OK]    $_pkg: $_out" || \
            { echo "[ERROR] $_pkg: $_out"; _VERIFY_FAIL=1; }
    done <<< "$_VERIFY_LINES"

    echo ""
    if [[ $_VERIFY_FAIL -eq 0 ]]; then
        echo "[INFO] All packages verified successfully."
    else
        echo "[ERROR] Some packages failed verification. Review the [ERROR] lines above."
    fi

    echo ""
    check_conda_uv_consistency

    echo ""
    echo "[INFO] Lerobot-Xense installation complete."
    exit $_VERIFY_FAIL
elif [[ "$1" == "--help" || "$1" == "-h" ]]; then
    print_general_usage
    exit 0

else
    echo "Invalid argument."
    print_general_usage
    exit 1
fi
