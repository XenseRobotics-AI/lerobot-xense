    if [[ -f "$QXCB" ]]; then
        echo "[xense] Removing OpenCV bundled Qt plugin: $QXCB"
        rm -f "$QXCB"
    fi

    if python - <<'PY'
from xensesdk.flash.linux_backend import LinuxFlashBackend
raise SystemExit(0 if LinuxFlashBackend().available else 1)
PY
    then
        echo "[xense] xensesdk flash backend (libxense_c) is available."
    else
        echo "[xense] ERROR: xensesdk flash backend verification failed."
        return 1
    fi

    echo "[xense] Done. Verify with: python -c 'import xensesdk; print(xensesdk)'"
}

# ── Hardware module: TacCap gripper SDK (xense.taccap) ───────────────────────

install_taccap() {
    echo ""
    echo "══════════════════════════════════════════"
    echo " TacCap-Gripper SDK  →  xense.taccap"
    echo "══════════════════════════════════════════"

    local SDK_DIR="$PROJECT_ROOT/third_party/taccap-gripper"
    if [[ ! -f "$SDK_DIR/pyproject.toml" ]]; then
        echo "ERROR: $SDK_DIR not found (submodule not initialized)."
        echo "  Run: git submodule update --init --recursive third_party/taccap-gripper"
        return 1
    fi
    # Nested libxensesdk (lite C++ vision dep) must be present for the cmake build.
    if [[ ! -f "$SDK_DIR/third_party/libxensesdk/CMakeLists.txt" ]]; then
        echo "[taccap] Initializing nested libxensesdk submodule..."
        git -C "$SDK_DIR" submodule update --init --recursive || {
            echo "[taccap] ERROR: failed to init libxensesdk submodule."
            return 1
        }
    fi

    # Tactile path uses libxense/pyudev, same find_library("udev") pitfall as xensesdk.
    fix_udev_discovery

    # taccap's libxense-lite C++ build needs the OpenCV C++ headers and
    # nlohmann_json, which the lerobot env does NOT ship (it carries only the
    # cv2 wheel, not libopencv C++). These are now declared in
    # conda_environment.yaml so the env-create solves them together with the
    # robostack ROS stack (one coherent solve) — this fallback normally no-ops
    # because the guard below finds the headers already present.
    # eigen/openssl/cmake/ninja/gcc14 are already present. libopencv is the C++
    # runtime only — it does not disturb the pip-installed opencv-python.
    # Note: the env carries `libzlib` (runtime) but not `zlib` (dev) — the latter
    # provides the linkable libz.so symlink that libxensesdk's find_package(ZLIB)
    # needs (CMakeLists.txt:321). Trigger on a missing libz.so too.
    if [[ ! -f "${CONDA_PREFIX}/include/nlohmann/json.hpp" ]] || \
       ! compgen -G "${CONDA_PREFIX}/include/opencv4/opencv2/opencv.hpp" > /dev/null 2>&1 || \
       [[ ! -e "${CONDA_PREFIX}/lib/libz.so" ]]; then
        echo "[taccap] Installing C++ build deps (libopencv, nlohmann_json, zlib, pkg-config, make)..."
        # Include robostack-staging and DO NOT pin libopencv=4.12: a bare
        # conda-forge solve with that pin pulls libprotobuf 6.31 and evicts the
        # robostack ROS stack (ros-humble-kdl-parser → breaks pyarx). 4.13 links
        # libprotobuf 6.33.5 and coexists with ros2-distro-mutex.
        ${CONDA_CMD:-mamba} install -c robostack-staging -c conda-forge -y \
            "libopencv>=4.13" "nlohmann_json=3.11.3" "zlib=1.3.1" pkg-config make
    fi

    # --no-build-isolation (used below to keep the build on the env's cmake/ninja
    # instead of a freshly fetched PyPI one) requires the PEP 517 backend and
    # pybind11 to be present in-env — pre-install them.
    uv pip install "scikit-build-core>=0.10" "pybind11>=2.12"

    # scikit-build-core + pybind11 build. LIBRARY_PATH gives the conda cross-
    # compiler the conda libdir (same reason as XGripper). --no-deps keeps the
    # shared env's numpy/opencv pins; --no-build-isolation uses the env's
    # cmake/ninja instead of a freshly fetched PyPI one.
    LIBRARY_PATH="${CONDA_PREFIX}/lib${LIBRARY_PATH:+:$LIBRARY_PATH}" \
        uv pip install -e "$SDK_DIR" --no-deps --no-build-isolation

    echo "[taccap] Done. Verify with: python -c 'import xense.taccap; print(xense.taccap.__file__)'"
}

# ── Hardware module: Elite CS (bi_elite_cs66_rt / elite_cs66_rt) ─────────────

install_elite() {
    echo ""
    echo "══════════════════════════════════════════"
    echo " Elite CS SDK (C++ + Python)  →  elite_cs_sdk"
    echo "══════════════════════════════════════════"

    local CPP_DIR="$PROJECT_ROOT/third_party/elite-robots-cs-sdk"
    local PY_DIR="$PROJECT_ROOT/third_party/elite-robots-cs-sdk-python"

    if [[ ! -f "$CPP_DIR/CMakeLists.txt" ]]; then
        echo "ERROR: $CPP_DIR not found."
        echo "  Run: git submodule update --init third_party/elite-robots-cs-sdk"
        return 1
    fi
    if [[ ! -f "$PY_DIR/CMakeLists.txt" ]]; then
        echo "ERROR: $PY_DIR not found."
        echo "  Run: git submodule update --init third_party/elite-robots-cs-sdk-python"
        return 1
    fi

    # C++ build prerequisites (system packages, see Elite BuildGuide):
    #   sudo apt install -y build-essential cmake libboost-all-dev libssh-dev \
    #                        libeigen3-dev liborocos-kdl-dev
    # Python build deps — the python_wheel target builds with --no-build-isolation.
    # Only the packages conda does NOT provide. pybind11, setuptools and wheel
    # all come from conda_environment.yaml; `uv pip install --upgrade` on them
    # overwrites conda's files in place, leaving conda-meta claiming a version
    # that is no longer on disk. The next `mamba env update` then relinks conda's
    # copy over uv's and leaves uv's extra files behind -- exactly how pip broke
    # with `ImportError: cannot import name 'get_runnable_pip'`.
    #
    # `--upgrade-package`, not `--upgrade`: uv's `--upgrade` drops the
    # prefer-installed rule for the WHOLE resolution, not just the named
    # packages. `--upgrade build` walked build's `packaging>=24.0` dependency
    # from conda's 26.2 to a 26.3 conda-forge does not ship (2026-09-01). `-P`
    # upgrades only the named packages and keeps every dependency where it is.
    uv pip install --upgrade-package pybind11-stubgen --upgrade-package build \
        pybind11-stubgen build

    # Build the pybind wheel, pointing the Python SDK at our LOCAL C++ SDK
    # submodule (ELITE_CS_SDK_REPO is required and must be a local path — the
    # Python build add_subdirectory()s it instead of fetching over the network).
    local BUILD_DIR="$PY_DIR/build"
    rm -rf "$BUILD_DIR"
    cmake -S "$PY_DIR" -B "$BUILD_DIR" \
        -DCMAKE_BUILD_TYPE=Release \
        -DELITE_CS_SDK_REPO="$CPP_DIR" \
        -DELITE_COMPILE_KIN_PLUGIN=ON \
        -DPython3_EXECUTABLE="$(which python)"
    cmake --build "$BUILD_DIR" --target python_wheel -j"$(nproc)"

    local WHEEL
    WHEEL="$(ls -t "$PY_DIR"/dist/elite_cs_sdk-*.whl 2>/dev/null | head -1)"
    if [[ -z "$WHEEL" ]]; then
        echo "[elite] ERROR: build did not produce a wheel under $PY_DIR/dist/"
        return 1
    fi
    uv pip install --force-reinstall "$WHEEL"

    echo "[elite] Done. Verify with: python -c 'import elite_cs_sdk; print(elite_cs_sdk.__file__)'"
}

