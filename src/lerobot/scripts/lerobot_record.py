def rebot_b601_rt_record_loop(
    robot: Robot,
    events: dict,
    fps: int,
    dataset: LeRobotDataset | None = None,
    teleop: Teleoperator | None = None,
    control_time_s: int | None = None,
    single_task: str | None = None,
    display_data: bool = False,
):
    """Single/dual B601 recording through the shared RT loop."""
    from lerobot.robots.rebot_b601_rt.tactile_camera import wait_for_fresh_camera_frames

    if fps <= 0:
        raise ValueError("B601 recording fps must be positive")
    policy = B601RecordPolicy(robot, teleop)
    if dataset is not None:
        # Encoder warmup can delay camera readers beyond the frame-age limit.
        # Wait before the episode clock starts, keeping the RT loop unchanged.
        wait_for_fresh_camera_frames(robot.cameras)
    run_rt_record_loop(
        robot,
        policy,
        events,
        fps,
        dataset=dataset,
        teleop=teleop,
        control_time_s=control_time_s if control_time_s is not None else float("inf"),
        single_task=single_task,
        display_data=display_data,
    )
    # A phase may end mid-reset. Finish it before the generic preparation loop
    # sends commands, and keep the native command watchdog refreshed while waiting.
    if policy.reset_pending:
        while robot.rt_moving:
            time.sleep(0.01)
        policy.resync(robot, teleop)


@parser.wrap()
def record(cfg: RecordConfig) -> LeRobotDataset:
    init_logging()
    logger.info(pformat(asdict(cfg)))
    if cfg.display_data:
        init_rerun(session_name="recording", ip=cfg.display_ip, port=cfg.display_port)
    display_compressed_images = (
        True
        if (cfg.display_data and cfg.display_ip is not None and cfg.display_port is not None)
        else cfg.display_compressed_images
    )

    # Elite CS66 wrists have tighter joint-velocity limits than Flexiv; default the
    # bi_pico4 rotation sensitivity to 0.5 so controller jitter can't drive a
    # protective stop. An explicit --teleop.ori_sensitivity wins.
    if (
        cfg.robot.type == "bi_elite_cs66_rt"
        and cfg.teleop is not None
        and cfg.teleop.type == "bi_pico4"
        and cfg.teleop.ori_sensitivity == 1.0
    ):
        cfg.teleop.ori_sensitivity = 0.5

    robot = make_robot_from_config(cfg.robot)
    if cfg.teleop is not None and (cfg.robot.type, cfg.teleop.type) in (
        ("elite_cs66_rt", "pico4"),
        ("bi_elite_cs66_rt", "bi_pico4"),
    ):
        from lerobot.robots.bi_elite_cs66_rt.pico4 import make_elite_pico4_teleoperator

        teleop = make_elite_pico4_teleoperator(cfg.teleop, robot)
    else:
        teleop = make_teleoperator_from_config(cfg.teleop) if cfg.teleop is not None else None

    teleop_type = cfg.teleop.type if cfg.teleop is not None else None
    use_raw_passthrough = _use_raw_passthrough_record(cfg.robot.type, teleop_type)

    if use_raw_passthrough:
        dataset_features = _build_raw_passthrough_dataset_features(robot, cfg.dataset.video)
    else:
        dataset_features = combine_feature_dicts(
            hw_to_dataset_features(robot.action_features, prefix=ACTION, use_video=cfg.dataset.video),
            hw_to_dataset_features(robot.observation_features, prefix=OBS_STR, use_video=cfg.dataset.video),
        )

    dataset = None
    listener = None
    record_error: BaseException | None = None

    try:
        if cfg.resume:
            dataset = LeRobotDataset(
                cfg.dataset.repo_id,
                root=cfg.dataset.root,
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                vcodec=cfg.dataset.vcodec,
                streaming_encoding=cfg.dataset.streaming_encoding,
                encoder_queue_maxsize=cfg.dataset.encoder_queue_maxsize,
                encoder_threads=cfg.dataset.encoder_threads,
            )

            if hasattr(robot, "cameras") and len(robot.cameras) > 0:
                dataset.start_image_writer(
                    num_processes=cfg.dataset.num_image_writer_processes,
                    num_threads=cfg.dataset.num_image_writer_threads_per_camera * len(robot.cameras),
                )
            sanity_check_dataset_robot_compatibility(dataset, robot, cfg.dataset.fps, dataset_features)
        else:
            # Create empty dataset or load existing saved episodes
            sanity_check_dataset_name(cfg.dataset.repo_id)
            dataset = LeRobotDataset.create(
                cfg.dataset.repo_id,
                cfg.dataset.fps,
                root=cfg.dataset.root,
                robot_type=robot.name,
                features=dataset_features,
                use_videos=cfg.dataset.video,
                image_writer_processes=cfg.dataset.num_image_writer_processes,
                image_writer_threads=cfg.dataset.num_image_writer_threads_per_camera * len(robot.cameras),
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                vcodec=cfg.dataset.vcodec,
                streaming_encoding=cfg.dataset.streaming_encoding,
                encoder_queue_maxsize=cfg.dataset.encoder_queue_maxsize,
                encoder_threads=cfg.dataset.encoder_threads,
            )

        # Vendor-specific robot.connect dispatch
        if teleop_type == "pico4" and cfg.robot.type == "flexiv_rizon4_rt":
            robot.connect(go_to_start=True)
            logger.info(f"Start EEF pose: {robot.get_current_tcp_pose_quat()}")
        elif (
            teleop_type == "bi_pico4"
            and cfg.robot.type in ("bi_flexiv_rizon4_rt", "bi_elite_cs66_rt")
            and teleop is not None
        ):
            try:
                with ThreadPoolExecutor(max_workers=2) as executor:
                    robot_future = executor.submit(robot.connect, go_to_start=True)
                    teleop_future = executor.submit(teleop.pre_init)
                    teleop_future.result()
                    robot_future.result()
            except KeyboardInterrupt:
                logger.info("Startup interrupted by user")
                raise

            left_pose, right_pose = robot.get_current_tcp_pose_quat()
            logger.info(f"Left start pose:  {left_pose}")
            logger.info(f"Right start pose: {right_pose}")
        elif cfg.robot.type == "elite_cs66_rt" and teleop_type in ("spacemouse", "pico4"):
            robot.connect(go_to_start=True)
            start_obs = robot.get_observation()
            tcp_keys = [k for k in start_obs if k.startswith("tcp.")]
            logger.info("Start pose: " + ", ".join(f"{k}={start_obs[k]:.6f}" for k in tcp_keys))
        else:
            robot.connect()

        # Vendor-specific teleop.connect dispatch
        if teleop is not None:
            if teleop_type == "pico4" and cfg.robot.type == "flexiv_rizon4_rt":
                teleop.connect(current_tcp_pose_quat=robot.get_current_tcp_pose_quat())
                logger.info("Teleop initialized with robot EEF pose.")
            elif teleop_type == "bi_pico4" and cfg.robot.type in (
                "bi_flexiv_rizon4_rt",
                "bi_elite_cs66_rt",
            ):
                left_pose, right_pose = robot.get_current_tcp_pose_quat()
                teleop.connect(left_tcp_pose_quat=left_pose, right_tcp_pose_quat=right_pose)
                logger.info("BiPico4 initialized with both robot EEF poses.")
            elif cfg.robot.type == "elite_cs66_rt" and teleop_type == "spacemouse":
                teleop.connect(current_tcp_pose_euler=robot.get_current_tcp_pose_euler())
                logger.info("Elite CS66 + SpaceMouse: teleop seeded from current TCP pose")
            elif cfg.robot.type == "elite_cs66_rt" and teleop_type == "pico4":
                teleop.connect(current_tcp_pose_quat=robot.get_current_tcp_pose_quat())
                logger.info("Elite CS66 + Pico4: teleop seeded from current TCP pose")
            elif cfg.robot.type == "rebot_b601_rt" and teleop_type == "spacemouse":
                teleop.connect(current_tcp_pose_euler=robot.get_commanded_tcp_pose_euler())
                logger.info("B601 + SpaceMouse: teleop seeded from commanded TCP pose")
            elif cfg.robot.type == "rebot_b601_rt" and teleop_type == "pico4":
                teleop.connect(current_tcp_pose_quat=robot.get_commanded_tcp_pose_quat())
                logger.info("B601 + Pico4: teleop seeded from commanded TCP pose")
            elif cfg.robot.type == "bi_rebot_b601_rt" and teleop_type == "bi_pico4":
                left_pose, right_pose = robot.get_commanded_tcp_pose_quat()
                teleop.connect(left_tcp_pose_quat=left_pose, right_tcp_pose_quat=right_pose)
                logger.info("BiB601 + BiPico4: teleop seeded from both commanded TCP poses")
            else:
                teleop.connect()

        listener, events = init_keyboard_listener(teleop=teleop)

        if not cfg.dataset.streaming_encoding:
            logger.info(
                "Streaming encoding is disabled. If you have capable hardware, consider enabling it for way faster episode saving. --dataset.streaming_encoding=true --dataset.encoder_threads=2 # --dataset.vcodec=auto. More info in the documentation: https://huggingface.co/docs/lerobot/streaming_video_encoding"
            )

        with VideoEncodingManager(dataset):
            recorded_episodes = 0
            while recorded_episodes < cfg.dataset.num_episodes and not events["stop_recording"]:
                # Warm up the streaming encoder before the loop so the first frame
                # doesn't overrun on encoder/codec initialization.
                if dataset is not None:
                    dataset.prepare_episode_recording()

                # Discard any exit request that arrived while nothing was
                # reading events. The keyboard listener runs for the whole
                # session, but only the record/reset loops consume these flags —
                # between the reset loop ending and the next episode starting
                # there is a gap (save_episode + the encoder warm-up above) with
                # no consumer, ~2s with streaming encoding and much longer
                # without it.
                #
                # A right arrow in that gap — the natural double-press when the
                # reset happens to time out on its own just as the operator
                # reaches for the key — is still set when this episode's first
                # iteration checks it. The episode ends after zero frames, the
                # reset then runs its full duration (the flag was consumed by
                # that break), and `save_episode()` below hits
                # `validate_episode_buffer`, which raises on an empty buffer:
                # "You must add one or several frames with `add_frame`". That
                # kills the session, mid-collection, minutes after the press —
                # with a normal-looking reset in between, which is what makes it
                # hard to connect back to a key someone pressed. Both record-loop
                # variants below reach it: the generic one breaks on `exit_early`
                # alone, the RT one on all three flags.
                #
                # `rerecord_episode` has a related hole — the RT loop breaks on it
                # without clearing it — but that one is self-correcting: the empty
                # buffer reaches `clear_episode_buffer()` instead of
                # `save_episode()` and the episode is simply retried. Cleared here
                # anyway so the operator does not see a "Re-record episode" for an
                # episode that never started.
                #
                # `stop_recording` is deliberately NOT cleared: that one should
                # survive the gap, and the `while` above has already acted on it.
                events["exit_early"] = False
                events["rerecord_episode"] = False

                log_say(f"Recording episode {dataset.num_episodes}", cfg.play_sounds)

                # Dispatch the record loop by robot type
                if cfg.robot.type == "elite_cs66_rt":
                    elite_cs66_rt_record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop=teleop,
                        dataset=dataset,
                        control_time_s=cfg.dataset.episode_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                    )
                elif cfg.robot.type in {
                    "flexiv_rizon4_rt",
                    "bi_flexiv_rizon4_rt",
                    "bi_elite_cs66_rt",
                }:
                    flexiv_rizon4_rt_record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop=teleop,
                        dataset=dataset,
                        control_time_s=cfg.dataset.episode_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                    )
                elif cfg.robot.type in {"rebot_b601_rt", "bi_rebot_b601_rt"}:
                    rebot_b601_rt_record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop=teleop,
                        dataset=dataset,
                        control_time_s=cfg.dataset.episode_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                    )
                else:
                    record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop=teleop,
                        dataset=dataset,
                        control_time_s=cfg.dataset.episode_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                        display_compressed_images=display_compressed_images,
                    )

                # Execute a few seconds without recording to give time to manually reset the environment
                # Skip reset for the last episode to be recorded
                if not events["stop_recording"] and (
                    (recorded_episodes < cfg.dataset.num_episodes - 1) or events["rerecord_episode"]
                ):
                    log_say("Reset the environment", cfg.play_sounds)

                    record_loop(
                        robot=robot,
                        events=events,
                        fps=cfg.dataset.fps,
                        teleop=teleop,
                        control_time_s=cfg.dataset.reset_time_s,
                        single_task=cfg.dataset.single_task,
                        display_data=cfg.display_data,
                    )

                if events["rerecord_episode"]:
                    log_say("Re-record episode", cfg.play_sounds)
                    events["rerecord_episode"] = False
                    events["exit_early"] = False
                    dataset.clear_episode_buffer()
                    continue

                dataset.save_episode()
                recorded_episodes += 1
    except KeyboardInterrupt:
        # Ctrl+C is how an operator ends a session, not a failure. Logging it
        # through the handler below would put an ERROR and a full traceback in
        # the session log for the ordinary case, which is exactly the noise
        # main() suppresses on the way out.
        logger.info("Recording interrupted by user (Ctrl+C)")
        raise
    except BaseException as error:
        record_error = error
        # Say why the recording stopped. Without this the only trace is the
        # "Stop recording" line below, and a session that died one second in
        # looks exactly like one the operator ended — the log carried neither
        # the exception nor a traceback.
        logger.error(f"Recording stopped by an error:\n{traceback.format_exc()}")
        raise
    finally:
        log_say("Stop recording", cfg.play_sounds, blocking=True)

        if dataset:
            dataset.finalize()

        if cfg.robot.type in {"rebot_b601_rt", "bi_rebot_b601_rt"}:
            # B601 is_connected also requires every camera/gripper, so a dropped
            # peripheral must not skip closing the arm. disconnect() is idempotent
            # and applies the same exit-reset policy as lerobot-teleoperate.
            from lerobot.robots.rebot_b601_rt.exit_policy import exit_reset_allowed

            robot.disconnect(reset=exit_reset_allowed(record_error))
        elif robot.is_connected:
            robot.disconnect()
        if teleop and teleop.is_connected:
            teleop.disconnect()

        if not is_headless() and listener:
            listener.stop()

        # Guarded like finalize() above: this runs in `finally`, so it also runs
        # when the dataset was never created — and an unguarded call there
        # raises AttributeError on None, replacing the real failure with one
        # that points nowhere near it.
        #
        # The upload is also not allowed to become the failure. It is the last
        # step, it depends on a network the recording did not, and raising here
        # discards whatever exception was already propagating — twice now the
        # reported error came from this line while the real one was never
        # printed. The episodes are on disk either way; `lerobot-record` can be
        # re-run with push only, or the dataset pushed by hand.
        if cfg.dataset.push_to_hub and dataset is not None:
            try:
                dataset.push_to_hub(tags=cfg.dataset.tags, private=cfg.dataset.private)
            except Exception as e:
                logger.error(f"Recording is saved at {dataset.root}, but pushing it to the Hub failed: {e!r}")

        log_say("Exiting", cfg.play_sounds)
    return dataset


def main():
    register_third_party_plugins()
    try:
        record()
    except KeyboardInterrupt:
        # record()'s finally block has already finalized the dataset, disconnected
        # devices and pushed to hub before the exception propagates here, so there
        # is nothing left to clean up — just suppress the noisy traceback.
        logger.info("Recording interrupted by user (Ctrl+C). Cleanup already done.")


if __name__ == "__main__":
    main()
